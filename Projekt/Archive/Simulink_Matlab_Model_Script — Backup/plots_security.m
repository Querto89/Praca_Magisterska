function plots_security(p, omega_measured, omega_ref, attack_flag)

    omega_measured = omega_measured(:)';
    omega_ref      = omega_ref(:)';
    attack_flag    = attack_flag(:)';

    N = min([ ...
        length(omega_measured), ...
        length(omega_ref), ...
        length(attack_flag)]);

    omega_measured = omega_measured(1:N);
    omega_ref      = omega_ref(1:N);
    attack_flag    = attack_flag(1:N);

    t_vec = (0:N-1) * p.dt;

    %% =========================================================
    %  RESIDUUM
    %  =========================================================

    residual = ...
        abs(omega_measured - omega_ref);

    %% =========================================================
    %  OKNO
    %  =========================================================

    figure( ...
        'Name', ...
        'Digital Twin - analiza FDI', ...
        'NumberTitle', 'off', ...
        'Position', [150 100 850 750]);

    %% =========================================================
    %  1. PREDKOSC
    %  =========================================================

    subplot(3,1,1);

    plot( ...
        t_vec, ...
        omega_ref, ...
        'g--', ...
        'LineWidth', 1.8);

    hold on;

    plot( ...
        t_vec, ...
        omega_measured, ...
        'r-', ...
        'LineWidth', 1.2);

    xline( ...
        p.attack_start, ...
        ':k', ...
        'Poczatek FDI');

    title( ...
        'Porownanie predkosci: Digital Twin i pomiar');

    ylabel('\omega [rad/s]');

    legend( ...
        'Digital Twin', ...
        '\omega_{measured}', ...
        'Location', 'best');

    grid on;

    %% =========================================================
    %  2. RESIDUUM
    %  =========================================================

    subplot(3,1,2);

    plot( ...
        t_vec, ...
        residual, ...
        'b-', ...
        'LineWidth', 1.5);

    hold on;

    yline( ...
        p.residual_threshold, ...
        ':r', ...
        ['Prog = ', ...
         num2str(p.residual_threshold), ...
         ' rad/s'], ...
        'LineWidth', 1.5);

    xline( ...
        p.attack_start, ...
        ':k');

    title( ...
        'Residuum Digital Twin');

    ylabel( ...
        '| \omega_{measured} - \omega_{DT} |');

    grid on;

    %% =========================================================
    %  3. ALARM
    %  =========================================================

    subplot(3,1,3);

    stairs( ...
        t_vec, ...
        attack_flag, ...
        'LineWidth', 1.8);

    hold on;

    xline( ...
        p.attack_start, ...
        ':k');

    title( ...
        'Flaga detekcji ataku FDI');

    ylabel('Alarm');

    xlabel('Czas [s]');

    ylim([-0.2 1.2]);

    yticks([0 1]);

    grid on;

end